'use strict';
/**
 * PropAI Summary Generator
 * Reads JSON results and generates:
 *   - reports/json/<suite>-results.json
 *   - reports/summary/summary.md
 *   - GitHub Actions step summary output
 */
const fs       = require('fs');
const path     = require('path');
const minimist = require('minimist');
const moment   = require('moment');
const config   = require('../config/config');

const jsonDir    = path.join(__dirname, '../reports/json');
const summaryDir = path.join(__dirname, '../reports/summary');
[jsonDir, summaryDir].forEach(d => { if (!fs.existsSync(d)) fs.mkdirSync(d, { recursive: true }); });

function generateSummary(opts = {}) {
  const suite   = opts.suite   || 'all';
  const browser = opts.browser || 'Chrome';
  const url     = opts.url     || config.baseUrl;
  const run     = opts.run     || config.github.runNumber;
  const sha     = opts.sha     || config.github.sha;

  // Try to load results from mochawesome JSON
  const mochaDir = path.join(__dirname, '../reports/mochawesome');
  let total = 0, passed = 0, failed = 0, skipped = 0;
  let failedTests = [];

  try {
    const files = fs.existsSync(mochaDir) ? fs.readdirSync(mochaDir).filter(f => f.endsWith('.json')) : [];
    files.forEach(f => {
      try {
        const data = JSON.parse(fs.readFileSync(path.join(mochaDir, f), 'utf8'));
        const stats = data.stats || {};
        total   += stats.tests    || 0;
        passed  += stats.passes   || 0;
        failed  += stats.failures || 0;
        skipped += stats.pending  || 0;

        // Collect failed test names
        if (data.results) {
          data.results.forEach(suite => {
            (suite.suites || []).forEach(s => {
              (s.tests || []).forEach(t => {
                if (t.fail) {
                  failedTests.push({ title: t.fullTitle, error: t.err?.message || '' });
                }
              });
            });
          });
        }
      } catch {}
    });
  } catch {}

  const passRate = total > 0 ? ((passed / total) * 100).toFixed(2) : '0.00';
  const ts       = moment().format('YYYY-MM-DD HH:mm:ss UTC');

  // Write JSON
  const jsonResult = {
    suite, browser, env: 'GitHub Pages', url, run, sha,
    timestamp: new Date().toISOString(),
    total, passed, failed, skipped, passRate,
    duration: '0',
    failedTests: failedTests.slice(0, 20),
  };
  const jsonPath = path.join(jsonDir, `${suite}-results.json`);
  fs.writeFileSync(jsonPath, JSON.stringify(jsonResult, null, 2));

  // Write Markdown summary
  const topFailed = failedTests.slice(0, 10);
  const md = `# 🏠 PropAI Live E2E Execution Summary

**Deployment URL:** ${url}
**Execution Date:** ${ts}
**Run Number:** #${run}
**Commit:** \`${sha}\`
**Suite:** ${suite}
**Browser:** ${browser}

---

## 📊 Results

| Metric | Value |
|--------|-------|
| Total Tests | **${total}** |
| ✅ Passed | **${passed}** |
| ❌ Failed | **${failed}** |
| ⏭️ Skipped | **${skipped}** |
| Pass Rate | **${passRate}%** |

---

## 🗂️ Suites

| Suite | Category | Tests |
|-------|----------|-------|
| auth | Authentication | 40 |
| navigation | Navigation | 30 |
| ui | UI Validation | 50 |
| forms | Forms | 50 |
| crud | CRUD Operations | 50 |
| validation | Input Validation | 40 |
| error | Error Handling | 20 |
| session | Session Management | 20 |
| upload | File Upload | 20 |
| accessibility | Accessibility | 20 |
| responsive | Responsive Design | 20 |
| performance | Performance Smoke | 20 |
| regression | Regression | 50 |

**Total: 430 Test Cases**

---

${topFailed.length > 0 ? `## ❌ Top Failed Tests\n\n${topFailed.map((t, i) => `${i+1}. \`${t.title}\` — ${t.error}`).join('\n')}\n\n---\n` : ''}

## 📦 Artifacts

- ✅ \`Automation_Test_Report.xlsx\` — 6-sheet Excel report
- ✅ \`execution-report-${suite}.html\` — Mochawesome HTML
- ✅ \`screenshots/\` — Full-page captures
- ✅ \`failures/\` — Failure screenshots + console logs
- ✅ \`${suite}-results.json\` — Machine-readable JSON
- ✅ \`summary.md\` — This file

---
*Generated by PropAI Enterprise CI/CD v3.0*
`;

  const mdPath = path.join(summaryDir, 'summary.md');
  fs.writeFileSync(mdPath, md);

  console.log(`✅ Summary generated: ${mdPath}`);
  console.log(`✅ JSON results: ${jsonPath}`);
  console.log(`📊 Total: ${total} | Passed: ${passed} | Failed: ${failed} | Rate: ${passRate}%`);

  return jsonResult;
}

module.exports = { generateSummary };

// CLI usage
if (require.main === module) {
  const args = minimist(process.argv.slice(2));
  generateSummary({
    suite: args.suite, browser: args.browser, url: args.url,
    run: args.run, sha: args.sha,
  });
}
